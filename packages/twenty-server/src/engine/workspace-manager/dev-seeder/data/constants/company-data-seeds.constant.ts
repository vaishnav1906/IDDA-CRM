const COMPANY_DATA_SEEDS_GENERATED = (): CompanyDataSeed[] => {
  const ids = Object.values(COMPANY_DATA_SEED_IDS);
  const memberIds = Object.values(WORKSPACE_MEMBER_DATA_SEED_IDS);

  return ids.map((id, index) => {
    const chainIdx = index % CLINIC_CHAINS.length;
    const cityIdx =
      Math.floor(index / CLINIC_CHAINS.length) % INDIAN_CITIES.length;
    const typeIdx =
      Math.floor(index / (CLINIC_CHAINS.length * INDIAN_CITIES.length)) %
      CLINIC_TYPES.length;
    const chain = CLINIC_CHAINS[chainIdx];
    const city = INDIAN_CITIES[cityIdx];
    const type = CLINIC_TYPES[typeIdx];
    const memberIdx = index % memberIds.length;
    const memberId = memberIds[memberIdx];

    return {
      id,
      name: `${chain} ${city} ${type}`,
      domainNamePrimaryLinkUrl: `https://${chain.toLowerCase().replace(/ /g, '')}.${city.toLowerCase().replace(/ /g, '')}.in`,
      addressAddressCity: city,
      linkedinLinkPrimaryLinkUrl: `https://www.linkedin.com/company/${chain.toLowerCase().replace(/ /g, '-')}-${city.toLowerCase().replace(/ /g, '-')}`,
      createdBySource: 'MANUAL',
      createdByWorkspaceMemberId: memberId,
      createdByName: 'IDDA CRM',
      accountOwnerId: memberIds[index % 4] || memberIds[0],
      updatedBySource: 'MANUAL',
      updatedByWorkspaceMemberId: memberId,
      updatedByName: 'IDDA CRM',
      position: index + 1,
    };
  });
};

